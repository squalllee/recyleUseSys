<script setup lang="ts">
import { computed, defineComponent, h, onMounted, ref, watch, type PropType } from 'vue'
import MaterialNoSelect from '../components/MaterialNoSelect.vue'
import {
  createRepairableDevice,
  deleteRepairableDevice,
  getRepairableDeviceSubtree,
  getRepairableDevices,
  updateRepairableDevice,
  type RepairableDevice,
  type RepairableDeviceInput,
} from '../services/apiService'

const devices = ref<RepairableDevice[]>([])
const loading = ref(false)
const saving = ref(false)
const errorMessage = ref('')
const keyword = ref('')
const modalVisible = ref(false)
const editingDevice = ref<RepairableDevice | null>(null)
const collapsedDeviceIDs = ref<Set<string>>(new Set())
const loadedChildrenIDs = ref<Set<string>>(new Set())
const loadingChildrenIDs = ref<Set<string>>(new Set())
const autoGeneratedDeviceID = ref(false)
const selectedMaterialNo = ref<string | null>(null)
const hierarchyModalVisible = ref(false)
const hierarchyDevice = ref<RepairableDevice | null>(null)
const hierarchyExpandedIDs = ref<Set<string>>(new Set())
const loadedSubtreeIDs = ref<Set<string>>(new Set())
const hierarchyLoading = ref(false)
const hierarchyErrorMessage = ref('')
let hierarchyLoadToken = 0

type HierarchyNode = {
  device: RepairableDevice
  children: HierarchyNode[]
}

const HierarchyNodeView: any = defineComponent({
  name: 'HierarchyNodeView',
  props: {
    node: { type: Object as PropType<HierarchyNode>, required: true },
    expandedIds: { type: Object as PropType<Set<string>>, required: true },
    selectedId: { type: String, default: '' },
  },
  emits: {
    toggle: (_deviceID: string) => true,
  },
  setup(props, { emit }): (() => any) {
    return () => {
      const { device, children } = props.node
      const isExpanded = props.expandedIds.has(device.DeviceID)
      const isSelected = props.selectedId === device.DeviceID
      const levelName =
        device.HierarchyLevel === 0 ? '根節點' : device.HierarchyLevel === 1 ? '設備' : `L${device.HierarchyLevel - 1}`

      return h('li', { class: 'relative' }, [
        h('span', { class: 'absolute -left-5 top-6 h-px w-5 bg-slate-200' }),
        h(
          'div',
          {
            class: [
              'flex min-w-[260px] items-start gap-2 rounded-xl border px-3 py-2 shadow-sm transition-colors',
              isSelected
                ? 'border-blue-400 bg-blue-50 ring-2 ring-blue-100'
                : 'border-slate-200 bg-white hover:border-blue-300',
            ],
          },
          [
            children.length
              ? h(
                  'button',
                  {
                    type: 'button',
                    class: 'mt-1 shrink-0 rounded p-1 text-slate-400 hover:bg-slate-100 hover:text-slate-700',
                    'aria-label': isExpanded ? '收合下層' : '展開下層',
                    'aria-expanded': isExpanded,
                    onClick: () => emit('toggle', device.DeviceID),
                  },
                  [
                    h(
                      'svg',
                      {
                        class: ['h-4 w-4 transition-transform', { '-rotate-90': !isExpanded }],
                        fill: 'none',
                        stroke: 'currentColor',
                        viewBox: '0 0 24 24',
                      },
                      [h('path', { 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'stroke-width': '2', d: 'm19 9-7 7-7-7' })]
                    ),
                  ]
                )
              : h('span', { class: 'mt-1 h-6 w-6 shrink-0' }),
            h('div', { class: 'min-w-0 flex-1' }, [
              h('div', { class: 'flex items-center gap-2' }, [
                h('p', { class: 'truncate text-sm font-semibold text-slate-900' }, device.DeviceName),
                h('span', { class: 'shrink-0 rounded-full bg-blue-50 px-2 py-0.5 text-[11px] font-medium text-blue-700' }, levelName),
              ]),
              h('p', { class: 'font-mono text-xs text-slate-500' }, device.DeviceID),
              h('div', { class: 'mt-1 flex flex-wrap gap-x-3 gap-y-1 text-[11px] text-slate-500' }, [
                device.MaterialNo ? h('span', `料號：${device.MaterialNo}`) : null,
                device.SerialNumber ? h('span', `序號：${device.SerialNumber}`) : null,
              ]),
            ]),
          ]
        ),
        children.length && isExpanded
          ? h(
              'ul',
              { class: 'ml-5 mt-3 space-y-3 border-l-2 border-slate-200 pl-5' },
              children.map((child) =>
                h(HierarchyNodeView, {
                  node: child,
                  expandedIds: props.expandedIds,
                  selectedId: props.selectedId,
                  onToggle: (deviceID: string) => emit('toggle', deviceID),
                })
              )
            )
          : null,
      ])
    }
  },
})

const emptyForm = (): RepairableDeviceInput => ({
  DeviceID: '',
  DeviceName: '',
  MaterialNo: null,
  SerialNumber: null,
  CurrentLocationDeviceID: null,
})

const form = ref<RepairableDeviceInput>(emptyForm())

const filteredDevices = computed(() => {
  const search = keyword.value.trim().toLocaleLowerCase()
  if (!search) return devices.value
  return devices.value.filter((device) =>
    [
      device.DeviceID,
      device.DeviceName,
      device.MaterialNo,
      device.SerialNumber,
      device.CurrentLocationDeviceID,
      device.CurrentLocationDeviceName,
    ].some((value) => String(value ?? '').toLocaleLowerCase().includes(search))
  )
})

const deviceByID = computed(() => new Map(devices.value.map((device) => [device.DeviceID, device])))

const childrenByID = computed(() => {
  const result = new Map<string, RepairableDevice[]>()
  for (const device of devices.value) {
    if (!device.CurrentLocationDeviceID) continue
    const children = result.get(device.CurrentLocationDeviceID) || []
    children.push(device)
    result.set(device.CurrentLocationDeviceID, children)
  }
  for (const children of result.values()) {
    children.sort((left, right) => left.DeviceID.localeCompare(right.DeviceID))
  }
  return result
})

const visibleDevices = computed(() =>
  filteredDevices.value.filter((device) => {
    let parentID = device.CurrentLocationDeviceID
    while (parentID) {
      if (collapsedDeviceIDs.value.has(parentID)) return false
      parentID = deviceByID.value.get(parentID)?.CurrentLocationDeviceID || null
    }
    return true
  })
)

const locationOptions = computed(() =>
  devices.value.filter((device) => device.DeviceID !== editingDevice.value?.DeviceID)
)

const isRootForm = computed(() => !form.value.CurrentLocationDeviceID)
const materialSelectionValid = computed(
  () => !form.value.MaterialNo || selectedMaterialNo.value === form.value.MaterialNo
)

const materialNoModel = computed<string>({
  get: () => form.value.MaterialNo || '',
  set: (value) => {
    const normalized = value.trim()
    form.value.MaterialNo = normalized || null
    if (selectedMaterialNo.value !== normalized) selectedMaterialNo.value = null
  },
})

const nextSuffix = (matches: (device: RepairableDevice) => boolean) => {
  const maximum = devices.value.reduce((max, device) => {
    if (!matches(device)) return max
    const suffix = device.DeviceID.slice(-4)
    return /^\d{4}$/.test(suffix) ? Math.max(max, Number(suffix)) : max
  }, 0)
  return String(maximum + 1).padStart(4, '0')
}

const generatedDeviceID = computed(() => {
  if (editingDevice.value || !form.value.CurrentLocationDeviceID) return ''
  if (!form.value.MaterialNo) return ''

  const materialNo = form.value.MaterialNo
  const prefix = `${materialNo}_`
  return `${prefix}${nextSuffix(
    (device) =>
      device.MaterialNo === materialNo &&
      device.DeviceID.startsWith(prefix) &&
      device.DeviceID.length === prefix.length + 4
  )}`
})

const syncGeneratedDeviceID = () => {
  if (editingDevice.value) return
  if (!form.value.CurrentLocationDeviceID) {
    if (autoGeneratedDeviceID.value) form.value.DeviceID = ''
    autoGeneratedDeviceID.value = false
    return
  }

  if (!generatedDeviceID.value) {
    if (autoGeneratedDeviceID.value) form.value.DeviceID = ''
    autoGeneratedDeviceID.value = true
    return
  }

  form.value.DeviceID = generatedDeviceID.value
  autoGeneratedDeviceID.value = true
}

watch(
  () => [
    form.value.CurrentLocationDeviceID,
    form.value.MaterialNo,
    devices.value.map((device) => device.DeviceID).join('|'),
  ],
  syncGeneratedDeviceID
)

const hasChildren = (deviceID: string) => {
  const device = deviceByID.value.get(deviceID)
  return Boolean(device?.HasChildren || childrenByID.value.get(deviceID)?.length)
}

const mergeLoadedDevices = (records: RepairableDevice[]) => {
  const merged = new Map(devices.value.map((device) => [device.DeviceID, device]))
  for (const record of records) merged.set(record.DeviceID, record)
  devices.value = [...merged.values()].sort((left, right) => left.HierarchyPath.localeCompare(right.HierarchyPath))
}

const loadChildren = async (deviceID: string) => {
  if (loadedChildrenIDs.value.has(deviceID)) return true
  if (loadingChildrenIDs.value.has(deviceID)) return false

  const parent = deviceByID.value.get(deviceID)
  if (!parent) return false

  const loadingIDs = new Set(loadingChildrenIDs.value)
  loadingIDs.add(deviceID)
  loadingChildrenIDs.value = loadingIDs

  try {
    const result = await getRepairableDevices(deviceID)
    const children = result.map((child) => ({
      ...child,
      CurrentLocationDeviceID: deviceID,
      CurrentLocationDeviceName: parent.DeviceName,
      HierarchyLevel: parent.HierarchyLevel + 1,
      HierarchyPath: `${parent.HierarchyPath}${child.DeviceID}/`,
      HasChildren: Boolean(child.HasChildren),
    }))
    mergeLoadedDevices(children)

    const loadedIDs = new Set(loadedChildrenIDs.value)
    loadedIDs.add(deviceID)
    loadedChildrenIDs.value = loadedIDs

    const collapsedIDs = new Set(collapsedDeviceIDs.value)
    for (const child of children) {
      if (child.HasChildren) collapsedIDs.add(child.DeviceID)
    }
    collapsedDeviceIDs.value = collapsedIDs
    return true
  } catch (error) {
    errorMessage.value = `載入下層資料失敗：${(error as Error).message}`
    return false
  } finally {
    const nextLoadingIDs = new Set(loadingChildrenIDs.value)
    nextLoadingIDs.delete(deviceID)
    loadingChildrenIDs.value = nextLoadingIDs
  }
}

const toggleCollapsed = async (deviceID: string) => {
  if (loadingChildrenIDs.value.has(deviceID)) return

  if (collapsedDeviceIDs.value.has(deviceID)) {
    if (!(await loadChildren(deviceID))) return
    const expandedIDs = new Set(collapsedDeviceIDs.value)
    expandedIDs.delete(deviceID)
    collapsedDeviceIDs.value = expandedIDs
  } else {
    const collapsedIDs = new Set(collapsedDeviceIDs.value)
    collapsedIDs.add(deviceID)
    collapsedDeviceIDs.value = collapsedIDs
  }
}

const buildVisibleHierarchy = (device: RepairableDevice, visited = new Set<string>()): HierarchyNode => {
  const nextVisited = new Set(visited)
  nextVisited.add(device.DeviceID)
  const children = hierarchyExpandedIDs.value.has(device.DeviceID)
    ? (childrenByID.value.get(device.DeviceID) || [])
        .filter((child) => !nextVisited.has(child.DeviceID))
        .map((child) => buildVisibleHierarchy(child, nextVisited))
    : []

  return { device, children }
}

const ancestorChainFor = (device: RepairableDevice) => {
  const chain = [device]
  const visited = new Set([device.DeviceID])
  let current = device

  while (current.CurrentLocationDeviceID) {
    const parent = deviceByID.value.get(current.CurrentLocationDeviceID)
    if (!parent || visited.has(parent.DeviceID)) break
    chain.push(parent)
    visited.add(parent.DeviceID)
    current = parent
  }

  return chain
}

type HierarchyGraphNode = {
  device: RepairableDevice
  x: number
  y: number
  depth: number
  isSelected: boolean
  expandable: boolean
}

type HierarchyGraphLink = {
  id: string
  path: string
}

type HierarchyGraph = {
  width: number
  height: number
  nodes: HierarchyGraphNode[]
  links: HierarchyGraphLink[]
}

const hierarchyGraph = computed<HierarchyGraph | null>(() => {
  const selected = hierarchyDevice.value
  if (!selected) return null

  const focusedTree = buildVisibleHierarchy(selected)
  const ancestors = ancestorChainFor(selected)
  const columnGap = 310
  const rowGap = 86
  const nodeWidth = 224
  const nodeHeight = 72
  const nodeHalfWidth = nodeWidth / 2
  const nodeHalfHeight = nodeHeight / 2
  const marginX = 64
  const marginY = 64
  const rawNodes: HierarchyGraphNode[] = []
  const rawLinks: Array<{ sourceID: string; targetID: string }> = []
  let leafIndex = 0

  // A tidy horizontal mind-map: leaves are stacked vertically and every parent
  // is centered between its first and last visible child.
  const placeNode = (treeNode: HierarchyNode, depth: number): HierarchyGraphNode => {
    const childNodes = treeNode.children.map((child) => placeNode(child, depth + 1))
    const y = childNodes.length
      ? (childNodes[0].y + childNodes[childNodes.length - 1].y) / 2
      : leafIndex++ * rowGap
    const graphNode: HierarchyGraphNode = {
      device: treeNode.device,
      x: depth * columnGap,
      y,
      depth,
      isSelected: depth === 0,
      expandable: hasChildren(treeNode.device.DeviceID),
    }

    rawNodes.push(graphNode)
    for (const childNode of childNodes) {
      rawLinks.push({ sourceID: graphNode.device.DeviceID, targetID: childNode.device.DeviceID })
    }
    return graphNode
  }

  const selectedNode = placeNode(focusedTree, 0)

  // Add only the direct ancestor chain to the left of the selected node.
  // Other children of those ancestors are unrelated to the focused branch.
  for (let index = 1; index < ancestors.length; index += 1) {
    const ancestor = ancestors[index]
    const child = ancestors[index - 1]
    rawNodes.push({
      device: ancestor,
      x: -index * columnGap,
      y: selectedNode.y,
      depth: -index,
      isSelected: false,
      expandable: false,
    })
    rawLinks.push({ sourceID: ancestor.DeviceID, targetID: child.DeviceID })
  }

  const minX = Math.min(...rawNodes.map((node) => node.x - nodeHalfWidth))
  const maxX = Math.max(...rawNodes.map((node) => node.x + nodeHalfWidth))
  const minY = Math.min(...rawNodes.map((node) => node.y - nodeHalfHeight))
  const maxY = Math.max(...rawNodes.map((node) => node.y + nodeHalfHeight))
  const contentHeight = maxY - minY
  const width = Math.max(760, maxX - minX + marginX * 2)
  const height = Math.max(480, contentHeight + marginY * 2)
  const shiftX = marginX - minX
  const shiftY = (height - contentHeight) / 2 - minY
  const nodes = rawNodes.map((node) => ({ ...node, x: node.x + shiftX, y: node.y + shiftY }))
  const nodePositions = new Map(nodes.map((node) => [node.device.DeviceID, node]))
  const links = rawLinks.flatMap((link, index) => {
    const source = nodePositions.get(link.sourceID)
    const target = nodePositions.get(link.targetID)
    if (!source || !target) return []
    const sourceX = source.x + nodeHalfWidth
    const targetX = target.x - nodeHalfWidth
    const controlX = (sourceX + targetX) / 2
    const path = `M ${sourceX} ${source.y} C ${controlX} ${source.y} ${controlX} ${target.y} ${targetX} ${target.y}`
    return [{ id: `${link.sourceID}-${link.targetID}-${index}`, path }]
  })

  return {
    width,
    height,
    nodes,
    links,
  }
})

const openHierarchyView = async (device: RepairableDevice) => {
  const loadToken = ++hierarchyLoadToken
  hierarchyDevice.value = device
  hierarchyExpandedIDs.value = new Set()
  hierarchyErrorMessage.value = ''
  hierarchyLoading.value = true
  hierarchyModalVisible.value = true

  try {
    let focusedDevices: RepairableDevice[]
    if (loadedSubtreeIDs.value.has(device.DeviceID)) {
      focusedDevices = devices.value.filter(
        (item) => item.DeviceID === device.DeviceID || item.HierarchyPath.startsWith(device.HierarchyPath)
      )
    } else {
      const knownIDs = new Set(devices.value.map((item) => item.DeviceID))
      const relativeRootPath = `/${device.DeviceID}/`
      const result = await getRepairableDeviceSubtree(device.DeviceID)
      if (loadToken !== hierarchyLoadToken) return

      focusedDevices = result.map((item) => {
        if (item.DeviceID === device.DeviceID) {
          return {
            ...item,
            CurrentLocationDeviceID: device.CurrentLocationDeviceID,
            CurrentLocationDeviceName: device.CurrentLocationDeviceName,
            HierarchyLevel: device.HierarchyLevel,
            HierarchyPath: device.HierarchyPath,
            HasChildren: Boolean(item.HasChildren),
          }
        }
        const relativeSuffix = item.HierarchyPath.startsWith(relativeRootPath)
          ? item.HierarchyPath.slice(relativeRootPath.length)
          : `${item.DeviceID}/`
        return {
          ...item,
          HierarchyLevel: device.HierarchyLevel + item.HierarchyLevel,
          HierarchyPath: `${device.HierarchyPath}${relativeSuffix}`,
          HasChildren: Boolean(item.HasChildren),
        }
      })
      mergeLoadedDevices(focusedDevices)

      const loadedChildren = new Set(loadedChildrenIDs.value)
      const loadedSubtrees = new Set(loadedSubtreeIDs.value)
      const collapsedIDs = new Set(collapsedDeviceIDs.value)
      for (const item of focusedDevices) {
        loadedChildren.add(item.DeviceID)
        loadedSubtrees.add(item.DeviceID)
        if (!knownIDs.has(item.DeviceID) && item.HasChildren) collapsedIDs.add(item.DeviceID)
      }
      loadedChildrenIDs.value = loadedChildren
      loadedSubtreeIDs.value = loadedSubtrees
      collapsedDeviceIDs.value = collapsedIDs
    }

    if (loadToken !== hierarchyLoadToken) return
    hierarchyDevice.value = deviceByID.value.get(device.DeviceID) || device
    hierarchyExpandedIDs.value = new Set(
      focusedDevices.filter((item) => item.HasChildren).map((item) => item.DeviceID)
    )
  } catch (error) {
    if (loadToken !== hierarchyLoadToken) return
    hierarchyErrorMessage.value = `載入完整階層失敗：${(error as Error).message}`
  } finally {
    if (loadToken === hierarchyLoadToken) hierarchyLoading.value = false
  }
}

const closeHierarchyView = () => {
  hierarchyLoadToken += 1
  hierarchyModalVisible.value = false
  hierarchyDevice.value = null
  hierarchyExpandedIDs.value = new Set()
  hierarchyLoading.value = false
  hierarchyErrorMessage.value = ''
}

const toggleHierarchyNode = async (deviceID: string) => {
  if (loadingChildrenIDs.value.has(deviceID)) return

  if (hierarchyExpandedIDs.value.has(deviceID)) {
    const collapsedIDs = new Set(hierarchyExpandedIDs.value)
    collapsedIDs.delete(deviceID)
    hierarchyExpandedIDs.value = collapsedIDs
    return
  }

  if (!(await loadChildren(deviceID))) return
  const expandedIDs = new Set(hierarchyExpandedIDs.value)
  expandedIDs.add(deviceID)
  hierarchyExpandedIDs.value = expandedIDs
}

const expandAllHierarchy = () => {
  hierarchyExpandedIDs.value = new Set(
    devices.value.filter((device) => loadedChildrenIDs.value.has(device.DeviceID)).map((device) => device.DeviceID)
  )
}

const collapseAllHierarchy = () => {
  hierarchyExpandedIDs.value = new Set()
}

const loadDevices = async () => {
  loading.value = true
  errorMessage.value = ''
  try {
    const roots = (await getRepairableDevices(null)).map((device) => ({
      ...device,
      CurrentLocationDeviceID: null,
      CurrentLocationDeviceName: null,
      HierarchyLevel: 0,
      HierarchyPath: `/${device.DeviceID}/`,
      HasChildren: Boolean(device.HasChildren),
    }))
    devices.value = roots.sort((left, right) => left.DeviceID.localeCompare(right.DeviceID))
    collapsedDeviceIDs.value = new Set(
      roots.filter((device) => device.HasChildren).map((device) => device.DeviceID)
    )
    loadedChildrenIDs.value = new Set()
    loadedSubtreeIDs.value = new Set()
    loadingChildrenIDs.value = new Set()
    hierarchyExpandedIDs.value = new Set()
  } catch (error) {
    errorMessage.value = `載入可修件失敗：${(error as Error).message}`
  } finally {
    loading.value = false
  }
}

const openCreateModal = () => {
  editingDevice.value = null
  form.value = emptyForm()
  autoGeneratedDeviceID.value = false
  selectedMaterialNo.value = null
  errorMessage.value = ''
  modalVisible.value = true
}

const openEditModal = (device: RepairableDevice) => {
  editingDevice.value = device
  form.value = {
    DeviceID: device.DeviceID,
    DeviceName: device.DeviceName,
    MaterialNo: device.MaterialNo,
    SerialNumber: device.SerialNumber,
    CurrentLocationDeviceID: device.CurrentLocationDeviceID,
  }
  autoGeneratedDeviceID.value = false
  selectedMaterialNo.value = device.MaterialNo
  errorMessage.value = ''
  modalVisible.value = true
}

const closeModal = () => {
  if (saving.value) return
  modalVisible.value = false
  editingDevice.value = null
}

const onMaterialSelected = () => {
  selectedMaterialNo.value = form.value.MaterialNo
}

const normalizeForm = (): RepairableDeviceInput => ({
  DeviceID: form.value.DeviceID.trim(),
  DeviceName: form.value.DeviceName.trim(),
  MaterialNo: form.value.MaterialNo?.trim() || null,
  // SerialNumber is optional and may be entered manually.
  SerialNumber: form.value.SerialNumber?.trim() || null,
  CurrentLocationDeviceID: form.value.CurrentLocationDeviceID || null,
})

const saveDevice = async () => {
  const data = normalizeForm()
  if (!data.DeviceName) {
    errorMessage.value = '設備名稱為必填欄位'
    return
  }
  if (!editingDevice.value && !isRootForm.value) {
    if (!data.MaterialNo) {
      errorMessage.value = '非根節點必須先從 WMS_V1 選取料號'
      return
    }
    data.DeviceID = generatedDeviceID.value
    if (!data.DeviceID) {
      errorMessage.value = '請先選擇有效的目前位置'
      return
    }
  } else if (!data.DeviceID) {
    errorMessage.value = '根節點必須輸入 DeviceID'
    return
  }
  if (!materialSelectionValid.value) {
    errorMessage.value = '請從 WMS_V1 下拉選項選取有效料號'
    return
  }

  saving.value = true
  errorMessage.value = ''
  try {
    if (editingDevice.value) {
      await updateRepairableDevice(editingDevice.value.DeviceID, data)
    } else {
      await createRepairableDevice(data)
    }
    modalVisible.value = false
    editingDevice.value = null
    await loadDevices()
  } catch (error) {
    errorMessage.value = `儲存可修件失敗：${(error as Error).message}`
  } finally {
    saving.value = false
  }
}

const removeDevice = async (device: RepairableDevice) => {
  if (!globalThis.confirm(`確定要刪除「${device.DeviceName}（${device.DeviceID}）」嗎？`)) return

  errorMessage.value = ''
  try {
    await deleteRepairableDevice(device.DeviceID)
    await loadDevices()
  } catch (error) {
    errorMessage.value = `刪除可修件失敗：${(error as Error).message}`
  }
}

const levelLabel = (level: number) => {
  if (level === 0) return '根節點'
  if (level === 1) return '設備'
  return `L${level - 1}`
}

onMounted(loadDevices)
</script>

